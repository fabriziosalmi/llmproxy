"""scripts/check_lock_sync.py: the lock is compared by content, not by text."""

import subprocess
import sys
from pathlib import Path

SCRIPT = Path(__file__).resolve().parent.parent / "scripts" / "check_lock_sync.py"
H1 = "sha256:" + "1" * 64
H2 = "sha256:" + "2" * 64

# What our uv writes.
OURS = f"""# This file was autogenerated by uv via the following command:
#    uv pip compile requirements.in --generate-hashes -o requirements.txt
sentry-sdk==2.61.1 \\
    --hash={H1} \\
    --hash={H2}
    # via -r requirements.in
typing-extensions==4.16.0 \\
    --hash={H1}
    # via
    #   aiohttp
    #   starlette
"""

# The same resolution as Dependabot's uv wrote it on #230: extras kept on the
# pin, fewer `# via` lines, hashes in another order.
DEPENDABOT = f"""# This file was autogenerated by uv via the following command:
#    uv pip compile requirements.in --generate-hashes -o requirements.txt
sentry-sdk[fastapi]==2.61.1 \\
    --hash={H2} \\
    --hash={H1}
typing_extensions==4.16.0 \\
    --hash={H1}
"""


def run(tmp_path, committed, fresh):
    a, b = tmp_path / "committed.txt", tmp_path / "fresh.txt"
    a.write_text(committed)
    b.write_text(fresh)
    return subprocess.run([sys.executable, str(SCRIPT), str(a), str(b)], capture_output=True, text=True)


def test_same_resolution_written_differently_is_in_sync(tmp_path):
    res = run(tmp_path, DEPENDABOT, OURS)
    assert res.returncode == 0, res.stdout
    assert "2 packages" in res.stdout


def test_a_different_version_is_out_of_sync(tmp_path):
    res = run(tmp_path, OURS.replace("sentry-sdk==2.61.1", "sentry-sdk==2.72.0"), OURS)
    assert res.returncode == 1
    assert "sentry-sdk: lock has 2.72.0, resolution has 2.61.1" in res.stdout


def test_a_different_hash_set_is_out_of_sync(tmp_path):
    res = run(tmp_path, OURS.replace(f"    --hash={H2}\n", ""), OURS)
    assert res.returncode == 1
    assert "the hashes differ" in res.stdout


def test_an_empty_lock_is_never_in_sync(tmp_path):
    res = run(tmp_path, "", "")
    assert res.returncode != 0
    assert "no pinned requirements found" in res.stderr


def test_a_package_missing_from_the_lock_is_out_of_sync(tmp_path):
    committed = OURS.split("typing-extensions")[0]
    res = run(tmp_path, committed, OURS)
    assert res.returncode == 1
    assert "typing-extensions: in the resolution, missing from the lock" in res.stdout
